async function seed() {
  console.log('🌱 Seeding 15 new toy reviews...\n');

  // Create reviews without alternatives first
  for (const review of newReviews) {
    const { alternatives, ...rest } = review;
    await client.createOrReplace(rest);
    console.log(`  ✓ ${review.productName} (Safety: ${review.safetyScore})`);
  }

  // Patch alternatives
  for (const review of newReviews) {
    if (review.alternatives?.length > 0) {
      await client.patch(review._id).set({ alternatives: review.alternatives }).commit();
    }
  }
  console.log('\n  ✓ Alternatives linked');

  // Upload images
  console.log('\n🖼️  Uploading images...\n');
  for (const [reviewId, imageUrl] of Object.entries(imageMap)) {
    try {
      const resp = await fetch(imageUrl);
      if (!resp.ok) { console.log(`  ✗ ${reviewId}: HTTP ${resp.status}`); continue; }
      const buf = await resp.arrayBuffer();
      const asset = await client.assets.upload('image', Buffer.from(buf), {
        filename: `${reviewId}.jpg`,
        contentType: 'image/jpeg',
      });
      await client.patch(reviewId).set({
        mainImage: { _type: 'image', alt: reviewId.replace('review-', '').replace(/-/g, ' '), asset: { _type: 'reference', _ref: asset._id } }
      }).commit();
      console.log(`  ✓ ${reviewId}`);
    } catch (e) {
      console.log(`  ✗ ${reviewId}: ${e.message}`);
    }
  }

  console.log('\n✅ Done! You now have 20 toy reviews with images.');
}

seed().catch(err => { console.error('❌', err.message); process.exit(1); });
